    /// <summary>
    /// 根据故障码返回 (简短名称, 详细描述)。
    /// 未知故障码返回通用描述。
    /// </summary>
    public static (string Name, string Detail) Lookup(ushort code)
    {
        if (code == 0)
        {
            return ("无故障", "驱动器运行正常");
        }

        return _table.TryGetValue(code, out var entry)
            ? entry
            : ($"未知故障 0x{code:X4}", $"驱动器报告故障码 0x{code:X4}，请查阅驱动器手册或联系技术支持");
    }

    /// <summary>
    /// 根据故障码返回简短名称。
    /// </summary>
    public static string GetName(ushort code) => Lookup(code).Name;

    /// <summary>
    /// 根据故障码返回详细描述。
    /// </summary>
    public static string GetDetail(ushort code) => Lookup(code).Detail;
}
